#!/usr/bin/env python3
"""tools/gen_android_table.py FRAMEWORKS_BASE > src/android_table.inc

Android's public resource table, for `apkpack link` in place of android.jar:
every public attribute (its ID, its formats, its enum and flag values) and
every other public resource (@android:style/..., @android:color/...), from
AOSP's frameworks/base (Apache-2.0):

  core/res/res/values/public-final.xml           the IDs, final
  core/res/res/values/attrs.xml, attrs_manifest.xml   the formats and values

The output is C++: two arrays apkpack.android includes. Run it again, from a
newer frameworks/base, when a newer API's attributes are needed."""
import re, subprocess, sys
import xml.etree.ElementTree as ET

base = sys.argv[1].rstrip("/")
values = f"{base}/core/res/res/values"

FORMATS = ["reference", "string", "integer", "boolean", "color", "float", "dimension", "fraction", "enum", "flags"]

public = ET.parse(f"{values}/public-final.xml").getroot()
attrs, others = {}, []
for p in public.iter("public"):
    t, name, ident = p.get("type"), p.get("name"), p.get("id")
    if not (t and name and ident):
        continue
    if t == "attr":
        attrs[name] = int(ident, 16)
    else:
        others.append((t, name, int(ident, 16)))

formats, values_of = {}, {}
for f in ("attrs.xml", "attrs_manifest.xml"):
    for a in ET.parse(f"{values}/{f}").getroot().iter("attr"):
        name = a.get("name")
        if not name or name.startswith("android:"):
            continue
        fmt = set((a.get("format") or "").split("|")) - {""}
        enums = [(e.get("name"), int(e.get("value"), 0) & 0xffffffff) for e in a.findall("enum")]
        flags = [(e.get("name"), int(e.get("value"), 0) & 0xffffffff) for e in a.findall("flag")]
        if enums:
            fmt.add("enum")
        if flags:
            fmt.add("flags")
        if fmt:
            formats[name] = formats.get(name, set()) | fmt
        if enums or flags:
            values_of[name] = enums + flags

try:
    rev = subprocess.run(["git", "-C", base, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
except OSError:
    rev = "unknown"
print("// Generated by tools/gen_android_table.py from AOSP frameworks/base")
print(f"// {rev} (Apache-2.0: NOTICE.android). Do not edit; generate again.")
print("// {name, id, formats (bit i: FORMATS[i]), first value, value count}")
print("inline constexpr std::string_view format_names[] = {" + ", ".join(f'"{f}"' for f in FORMATS) + "};")
vals = []
print("inline constexpr AttrInfo attr_table[] = {")
for name in sorted(attrs, key=lambda n: attrs[n]):
    bits = sum(1 << i for i, f in enumerate(FORMATS) if f in formats.get(name, set()))
    vs = values_of.get(name, [])
    print(f'    {{"{name}", {attrs[name]:#010x}, {bits:#06x}, {len(vals)}, {len(vs)}}},')
    vals.extend(vs)
print("};")
print("inline constexpr NamedValue attr_values[] = {")
for n, v in vals:
    print(f'    {{"{n}", {v:#010x}}},')
print("};")
print("inline constexpr PublicResource public_table[] = {")
for t, n, i in sorted(others, key=lambda x: x[2]):
    print(f'    {{"{t}", "{n}", {i:#010x}}},')
print("};")
